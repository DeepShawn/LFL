export function objective(state) {
  const flags = state.flags || {};
  if (state.scene === 'tutorial' || state.mode === 'tutorial') {
    const tutorial = state.tutorial || {};
    const keys = ['moved', 'switched', 'light', 'inspected', 'puzzle', 'recovered', 'water', 'escaped', 'retried'];
    const index = keys.findIndex(key => !tutorial[key]);
    return index === -1 ? '演习项目已完成，点击“完成教程”返回主菜单，选择正式夜行。' : TUTORIAL_STEPS[index];
  }
  if (!flags.archive) return '从北门沿主路前往行政楼，核对纸背路线，打开档案柜取出名册原件。';
  if (!flags.circuit) return '前往实验楼，按检修记录处理本楼分路，并观察机械校铃与门闩。';
  if (!flags.seat) return '前往教学楼，按旧座位表找到林舟真正的座位。';
  if (!flags.pass) return '前往宿舍，核对三片签离联的纸背压痕，拼回旧凭。';
  if (!flags.name) return '前往食堂，照纸背旧句布置归名桌，取回自己的旧姓名条。';
  if (!flags.echoes) return '你已可去北门凭旧联与旧名离校，若要结束循环，可先在食堂回声台归还其余旧应答。';
  if (!flags.power) return '回到行政楼广播总控，保留铃灯、关闭重复播送，再前往北门。';
  return '旧应答已归册、重复播送已停止，请到北门以旧联与旧名核验离校，不必新签。';
}
